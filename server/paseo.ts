import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { randomUUID } from 'node:crypto';
import { createPaseoClient, type PaseoClient, type PaseoAgent } from '@getpaseo/client';
import type { BridgeConfig } from './config.js';
import { DaemonClient } from '@getpaseo/client/internal/daemon-client';
import { loadRoute } from './codex-native.js';

const configurations = new WeakMap<PaseoClient, BridgeConfig>();

async function credential(config: BridgeConfig): Promise<string> {
  const lock = JSON.parse(await readFile(join(config.paseoHome, 'paseo.pid'), 'utf8'));
  const selected = new URL(config.paseoUrl);
  const published = new URL('ws://' + lock.listen + '/ws');
  const normalized = (host: string) => ['localhost', '127.0.0.1', '[::1]'].includes(host) ? 'loopback' : host;
  if (selected.username || selected.password || selected.pathname !== '/ws' || selected.port !== published.port || normalized(selected.hostname) !== normalized(published.hostname)) {
    throw new Error('The Paseo endpoint does not match this daemon home. Its local credential was not sent.');
  }
  // Same-user credential generated by this particular daemon. Never logged or persisted here.
  return (await readFile(config.paseoPasswordFile ?? join(config.paseoHome, 'local-credential'), 'utf8')).trim();
}

export async function connectPaseo(config: BridgeConfig): Promise<PaseoClient> {
  const password = await credential(config);
  const client = createPaseoClient({ url: config.paseoUrl, password, reconnect: { enabled: false }, connectTimeoutMs: 5000 });
  try{await client.connect();}catch(error){await client.close().catch(()=>{});throw error;}
  configurations.set(client, config); return client;
}

export async function connectPaseoDriver(config: BridgeConfig): Promise<DaemonClient> {
  const client = new DaemonClient({ url: config.paseoUrl, password: await credential(config), clientId: 'herdr-native-import-' + randomUUID(), reconnect: { enabled: false }, connectTimeoutMs: 5000 });
  try{await client.connect();}catch(error){await client.close().catch(()=>{});throw error;}
  return client;
}

/** Removed/archived workspaces can disappear from both active and History lists.
 * Their stored agent IDs are still readable through the official direct fetch. */
export async function includeKnownAgents(client:Pick<PaseoClient,'agents'>,listed:PaseoAgent[],ids:Array<string|undefined>):Promise<PaseoAgent[]>{
 const agents=new Map(listed.map(a=>[a.id,a]));
 const missing=[...new Set(ids.filter((id):id is string=>typeof id==='string'&&!!id))].filter(id=>!agents.has(id));
 for(let offset=0;offset<missing.length;offset+=8)await Promise.all(missing.slice(offset,offset+8).map(async id=>{
  try{const found=await client.agents.ref(id).refresh();if(found)agents.set(found.agent.id,found.agent);}
  catch(error){if(!/not found|not_found|unknown agent|does not exist|no agent/i.test(String((error as Error).message)))throw error;}
 }));
 return [...agents.values()];
}

export async function listBridgeAgents(client: PaseoClient): Promise<PaseoAgent[]> {
  const result: PaseoAgent[] = [];
  let cursor: string | undefined;
  do {
    const page = await client.agents.list({ filter: { includeArchived: true }, page: { limit: 100, cursor } });
    for (const entry of page.entries) {
      const config = configurations.get(client);
      const route = entry.agent.provider === 'codex' && config ? await loadRoute(config, entry.agent.id) : undefined;
      if (entry.agent.provider !== 'herdr' && !route) continue;
      const full = await client.agents.ref(entry.agent.id).refresh();
      if (full) result.push(route ? { ...full.agent, labels: { ...full.agent.labels, 'herdr.session-key': route.key, 'herdr.bridge': 'true' } } : full.agent);
    }
    cursor = page.pageInfo.nextCursor ?? undefined;
  } while (cursor);
  return result;
}

export function bridgeKey(agent: PaseoAgent): string | undefined {
  const label = agent.labels?.['herdr.session-key'];
  if (label) return label;
  const id = agent.persistence?.sessionId;
  if (id?.startsWith('plugin:')) {
    try { return JSON.parse(id.slice(7)).data?.key; } catch { return undefined; }
  }
  return undefined;
}
